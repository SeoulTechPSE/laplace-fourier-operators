"""Build the TMLR submission of the (C) paper from the working paper `c_paper.qmd`.

    python experiments/C/paper/tmlr/make_tmlr.py      # writes c_paper_tmlr.qmd and renders c_paper_tmlr.pdf

The working paper stays the source; this script only changes what the venue requires:

- TMLR style, pdflatex (as TMLR's template; its T1 / lmodern setup breaks unicode-math under LuaLaTeX), (`tmlr/tmlr.sty`, `tmlr/tmlr.bst`, JmlrOrg/tmlr-style-file 7bf90ef, Apache-2.0): 10 pt article,
  letter paper, anonymous ("Anonymous authors / Paper under double-blind review"), natbib author-year citations.
- One-paragraph abstract (`tmlr/abstract.md`), as TMLR asks; the working paper's abstract section is dropped.
- References before the appendix; the appendix lettered.
- TMLR submissions and reviews are public on OpenReview, so the summary of the unpublished follow-up study is
  replaced by one neutral sentence, with the release's rules (`release/make_release.py`, REPLACE_TEXT).
"""
from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent
ROOT = PAPER.parents[2]
SRC, OUT = PAPER / "c_paper.qmd", PAPER / "c_paper_tmlr.qmd"


def release_rules():
    spec = importlib.util.spec_from_file_location("make_release", ROOT / "release" / "make_release.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    rules = []
    for line in mod.REPLACE_TEXT.splitlines():
        if "==>" not in line:
            continue
        old, new = line.split("==>", 1)
        if old.startswith("regex:"):
            rules.append((re.compile(old[6:]), new.replace("\\n", "\n")))
        else:
            rules.append((old, new))
    return rules


def neutralize(text: str) -> str:
    for old, new in release_rules():
        text = old.sub(lambda m: new, text) if isinstance(old, re.Pattern) else text.replace(old, new)
    return text


def main():
    src = SRC.read_text()
    m = re.match(r"---\n(.*?)\n---\n", src, re.S)
    title = re.search(r'^title: "(.*)"$', m.group(1), re.M).group(1)
    body = src[m.end():]
    body = re.sub(r"<!--.*?-->\n", "", body, count=1, flags=re.S)             # header comment (source paths)
    i, j = body.index("## Abstract {.unnumbered}"), body.index("## Introduction")
    body = body[:i] + body[j:]
    refs = "## References {.unnumbered}\n\n::: {#refs}\n:::\n"
    assert refs in body
    body = body.replace(refs, "```{=latex}\n\\bibliography{references}\n"
                              "\\clearpage\n\\appendix\n```\n")
    body = body.replace("## Appendix: full grid of the linear audit {.unnumbered}", "## Full grid of the linear audit")
    body = neutralize(body)
    caption = "Pass numbers refer to `experiments/C/e5_probe/README.md`."
    assert caption in body, caption
    body = body.replace(caption, "Pass numbers refer to the probe experiments' README in the code release.")
    for bad in ("Kee-Youn", "Yoo", "SeoulTech", "github.com"):
        assert bad not in body, bad
    for old, _ in release_rules():                 # every neutralized passage is gone
        assert not (old.search(body) if isinstance(old, re.Pattern) else old in body), old
    abstract = (HERE / "abstract.md").read_text().strip()
    assert "\n\n" not in abstract, "TMLR: one-paragraph abstract"
    yaml = f'''---
title: "{title}"
abstract: |
  {abstract}
format:
  pdf:
    documentclass: article
    classoption: [10pt]
    number-sections: true
    tbl-colwidths: false
    cite-method: natbib
    biblio-style: tmlr/tmlr
    keep-tex: true
    colorlinks: true
    pdf-engine: pdflatex
    include-in-header:
      text: |
        \\usepackage{{tmlr/tmlr}}
        \\usepackage{{newunicodechar}}
        \\newunicodechar{{−}}{{\\ensuremath{{-}}}}
        \\newunicodechar{{±}}{{\\ensuremath{{\\pm}}}}
        \\newunicodechar{{×}}{{\\ensuremath{{\\times}}}}
        \\newunicodechar{{≈}}{{\\ensuremath{{\\approx}}}}
        \\newunicodechar{{→}}{{\\ensuremath{{\\rightarrow}}}}
        \\newunicodechar{{†}}{{\\dag}}
---

<!-- Generated by tmlr/make_tmlr.py from c_paper.qmd; edit the working paper, not this file. -->
'''
    OUT.write_text(yaml + body)
    subprocess.run(["quarto", "render", OUT.name, "--to", "pdf"], cwd=PAPER, check=True)
    print("wrote", OUT, OUT.with_suffix(".pdf"))


if __name__ == "__main__":
    main()
