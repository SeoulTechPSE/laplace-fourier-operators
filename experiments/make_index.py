"""Build `experiments/INDEX.md`: every experiment script with its title, the commit that added it, its result files
and its recorded compute time.

Under the project's protocol a script is committed with its predictions before it runs, so the commit that added
the script is its pre-registration (later fixes are listed in each folder's README). Compute time is the sum of
the `seconds` fields in the script's JSON results, where it records them.

    python experiments/make_index.py      # rewrites experiments/INDEX.md
"""
from __future__ import annotations

import ast
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def first_commit(path: Path) -> str:
    out = subprocess.run(["git", "log", "--diff-filter=A", "--follow", "--format=%h %ad", "--date=short", "--",
                          str(path.relative_to(ROOT))], cwd=ROOT, capture_output=True, text=True).stdout.split("\n")
    lines = [ln for ln in out if ln.strip()]
    return lines[-1] if lines else "uncommitted"


def title(path: Path) -> str:
    try:
        doc = ast.get_docstring(ast.parse(path.read_text())) or ""
    except SyntaxError:
        return ""
    line = doc.strip().split("\n")[0] if doc else ""
    return line.replace("|", "/")


def seconds(results: list[Path]) -> float:
    total = 0.0
    for p in results:
        if p.suffix != ".json":
            continue
        try:
            data = json.loads(p.read_text())
        except (json.JSONDecodeError, UnicodeDecodeError):
            continue
        rows = data if isinstance(data, list) else data.get("runs", []) if isinstance(data, dict) else []
        total += sum(r.get("seconds", 0.0) for r in rows if isinstance(r, dict))
    return total


def main():
    lines = ["# Experiment index", "",
             "Generated by `experiments/make_index.py`; do not edit by hand. The commit that added a script is its",
             "pre-registration (predictions in the docstring or the folder README). Compute: summed `seconds` of the",
             "JSON results where recorded (GPU wall time, often with another job on the GPU).", ""]
    for folder in sorted(p for p in HERE.glob("*/*") if p.is_dir() and any(p.glob("*.py"))):
        scripts = sorted(p for p in folder.glob("*.py") if not p.name.startswith("_"))
        if not scripts:
            continue
        lines += [f"## {folder.relative_to(HERE)}", "", "| script | added (pre-registration) | results | compute | title |",
                  "|---|---|---|---|---|"]
        for s in scripts:
            res = sorted((folder / "results").glob(s.stem + ".*")) if (folder / "results").exists() else []
            sec = seconds(res)
            comp = f"{sec / 3600:.1f} h" if sec >= 360 else (f"{sec / 60:.0f} min" if sec else "—")
            names = ", ".join(f"`{r.name}`" for r in res) or "—"
            lines.append(f"| `{s.name}` | {first_commit(s)} | {names} | {comp} | {title(s)} |")
        lines.append("")
    (HERE / "INDEX.md").write_text("\n".join(lines))
    print(f"wrote {HERE / 'INDEX.md'} ({sum(1 for ln in lines if ln.startswith('| `'))} scripts)")


if __name__ == "__main__":
    main()
